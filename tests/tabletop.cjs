const assert=require('assert');
const {runtime}=require('./studio.cjs');
const make=(mode='B')=>{const r=runtime('dist/index.html',mode);r.api.start(1,mode);return r};
const r=make();
assert(r.nodes.app.innerHTML.includes('tactile-mode'),'physical playtest surface is the default');
assert(r.nodes.app.innerHTML.includes('class="card-rail"'),'board and gap targets share one rail');
assert.equal((r.nodes.app.innerHTML.match(/data-slot="/g)||[]).length,10,'mode B shows all ten legal insertion seams');
assert(r.nodes.app.innerHTML.includes('id="tabletop-toggle"'),'guided fallback is available');
assert(r.nodes.app.innerHTML.includes('id="focus-toggle"'),'focus mode is available');
assert.equal(r.api.placeAt(0),false,'a bare gap tap should not accidentally commit a card');
assert.equal(r.api.game.pending,null,'without a lifted card there is no turn');
r.api.chooseHand(2);
const color=r.api.game.players[0].hand[2];
assert(r.api.placeAt(0),'tap hand then left edge must place immediately');
assert.equal(r.api.game.pending.move.pos,0);
assert.equal(r.api.game.pending.move.index,2);
assert.equal(r.api.game.pending.move.color,color);
const right=make('C');
right.api.chooseHand(0);
assert(right.api.placeAt(9),'rightmost slot must remain playable');
assert.equal(right.api.game.pending.move.pos,9);
const swapped=make('B');
swapped.api.arm('swap',swapped.api.game.players[0].hand[0]);
assert(swapped.api.placeAt(1),'selecting an adjacent pair stages SWAP');
assert.equal(swapped.api.game.draft.swapPos,1);
swapped.api.chooseHand(1);
assert(swapped.api.placeAt(4),'place after SWAP');
assert.equal(swapped.api.game.pending.move.swapPos,1);
assert.equal(swapped.api.game.pending.move.pos,4);
const wild=make('A');
wild.api.arm('wild',null);
assert.equal(wild.api.placeAt(3),false,'Wild needs an explicit color');
assert.equal(wild.api.game.pending,null);
wild.api.setSpecialColor('B');
assert(wild.api.placeAt(8),'Wild can be inserted at the right edge');
assert.equal(wild.api.game.pending.move.kind,'wild');
assert.equal(wild.api.game.pending.move.color,'B');
const guided=make('B');
guided.api.setTabletopMode(false);
assert(guided.nodes.app.innerHTML.includes('guided-mode'));
assert.equal((guided.nodes.app.innerHTML.match(/data-slot="/g)||[]).length,10,'guided mode retains every insertion position');
guided.api.placeAt(5);
assert.equal(guided.api.game.pending,null,'guided mode still requires confirmation');
assert(guided.nodes.app.innerHTML.includes('id="commit"'));
guided.api.setTabletopMode(true);
assert(guided.nodes.app.innerHTML.includes('tactile-mode'));
console.log('Tactile table, tap-to-place, both edges, staged Swap, Wild and guided fallback passed.');
