'use strict';
const assert=require('node:assert/strict');
const {measure,measurementAllowed,setMeasurementAllowed,CONSENT_KEY}=require('../apps/web/lib/product-measurement.ts');
const values=new Map();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)}});
globalThis.window={dispatchEvent(){}};
const calls=[];
globalThis.fetch=(...args)=>{calls.push(args);return Promise.resolve({ok:true});};
assert.equal(measurementAllowed(),false);
measure({event:'landing_view'});assert.equal(calls.length,0);
assert.equal(setMeasurementAllowed(true),true);assert.equal(values.get(CONSENT_KEY),'yes');
measure({event:'round_started',mode:'local',deck:'characters'});
assert.equal(calls.length,1);
const [url,options]=calls[0],payload=JSON.parse(options.body);
assert.equal(url,'/api/product-events');
assert.equal(options.credentials,'omit');assert.equal(options.referrerPolicy,'origin');
assert.deepEqual(Object.keys(payload).sort(),['deck','event','id','mode']);
assert.match(payload.id,/^[a-f0-9-]{36}$/);
assert.equal(setMeasurementAllowed(false),true);
measure({event:'landing_view'});assert.equal(calls.length,1);
console.log('Product measurement consent checks passed');
