"use strict";
const assert=require("node:assert/strict");
const {coachTip,roundOutcome}=require("../apps/web/lib/coach-core.cjs");
const game={phase:"play",moves:2,stockCount:20,legal:[{type:"play"},{type:"take"}],followup:[],slam:[],pendingCounter:null,pendingDump:null,limit:null,finishedOrder:[],loser:null};
const context={me:0,active:true,stage:"hand",selection:[],canPlay:false,needsTarget:false};
const tip=(g={},c={})=>coachTip({...game,...g},{...context,...c}).id;
assert.equal(tip({phase:"setup"}),"setup");
assert.equal(tip({moves:0}),"first");
assert.equal(tip({pendingCounter:{seat:0}}),"counter");
assert.equal(tip({pendingCounter:{seat:1}}),"wait-counter");
assert.equal(tip({pendingDump:{seat:0}}),"dump-target");
assert.equal(tip({pendingDump:{seat:1}}),"wait-dump");
assert.equal(tip({followup:[{type:"followup"}]},{active:false}),"snap");
assert.equal(tip({slam:[{type:"slam"}]},{active:false}),"slam");
assert.equal(tip({},{selection:[1],canPlay:false}),"blocked");
assert.equal(tip({},{selection:[1],canPlay:true,selectedAction:"dump"}),"dump");
assert.equal(tip({},{selection:[1],canPlay:true,selectedAction:"burn"}),"burn");
assert.equal(tip({legal:[{type:"take"}]}),"take");
assert.equal(tip({stockCount:0},{stage:"down"}),"blind");
assert.equal(tip({stockCount:0},{stage:"up"}),"face-up");
assert.equal(tip({stockCount:0}),"last-hand");
assert.equal(tip({limit:{type:"under"}}),"under");
assert.equal(tip({limit:{type:"min",value:7}}),"minimum");
assert.equal(coachTip({...game,phase:"over"},context),null);
const over={phase:"over",finishedOrder:[2,0],loser:1};
assert.equal(roundOutcome(over,2).kind,"first");
assert.equal(roundOutcome(over,0).kind,"escaped");
assert.equal(roundOutcome(over,1).kind,"loss");
assert.equal(roundOutcome(game,0),null);
console.log("PASS coach and results: authoritative interrupts, selection, stage, outcome");
