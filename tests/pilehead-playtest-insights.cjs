"use strict";
const assert = require("node:assert/strict");
const { createLog, observe, summarize, exportReport } = require("../apps/web/lib/playtest-insights-core.cjs");
const log = createLog();
const feed = (key, phase, mode = "local", drill = false) => observe(log, {key, phase, mode, drill});
feed("already-running", "play"); feed("already-running", "over");
feed("drill", "setup", "local", true); feed("drill", "play", "local", true); feed("drill", "over", "local", true);
feed("local:secret-seed", "setup"); feed("local:secret-seed", "play"); feed("local:secret-seed", "play");
feed("local:secret-seed", "over"); feed("local:secret-seed", "over"); feed("local:secret-seed", "play"); feed("local:secret-seed", "over");
feed("online:SECRETROOM:1", "setup", "online"); feed("online:SECRETROOM:1", "play", "online"); feed("online:SECRETROOM:1", "over", "online");
feed("online:SECRETROOM:2", "setup", "online"); feed("online:SECRETROOM:2", "play", "online");
assert.deepEqual(summarize(log), {local:{started:1,completed:1},online:{started:2,completed:1},truncated:false});
const report = exportReport(log, {fun:5, clarity:6, wouldReplay:"yes", secret:"private"});
assert.deepEqual(report.feedback,{fun:5,clarity:null,wouldReplay:"yes"});
assert.ok(!/SECRETROOM|secret-seed|private/.test(JSON.stringify(report)));
assert.deepEqual(summarize(createLog()), {local:{started:0,completed:0},online:{started:0,completed:0},truncated:false});
const capped = createLog();
for (let i=0;i<101;i++) observe(capped,{key:String(i),mode:"local",phase:"setup"});
assert.equal(capped.rounds.size,100);
assert.equal(summarize(capped).truncated,true);
console.log("Voluntary playtest observation: passed");
