'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const modules=[["index","index.js"],["./src/rules","src/rules.js"],["./bots","src/bots.js"],["./snapshot","src/snapshot.js"]];
function renderBrowserBundle(){
 const read=p=>fs.readFileSync(path.join(root,'packages/game-engine',p),'utf8');
 return "/* GENERATED by scripts/sync-game-engine.cjs; edit packages/game-engine instead. */\n(function(root){'use strict';\nconst modules={\n"+modules.map(([id,p])=>JSON.stringify(id)+":function(module,exports,require){\n"+read(p)+"\n}").join(",\n")+"\n};\nconst cache=Object.create(null);\nfunction load(id){if(cache[id])return cache[id].exports; if(!Object.prototype.hasOwnProperty.call(modules,id))throw Error('Unknown engine module '+id);const m={exports:{}};cache[id]=m;modules[id](m,m.exports,load);return m.exports;}\nconst api=load('index');\nroot.PileheadEngine=api;\nif(typeof module!=='undefined'&&module.exports)module.exports=api;\n})(typeof globalThis!=='undefined'?globalThis:this);\n";
}
function sync({check=false}={}){
 const file=path.join(root,'dist/pilehead/engine.js'),expected=renderBrowserBundle();
 if(check){if(fs.readFileSync(file,'utf8')!==expected)throw Error('Classic engine artifact stale: npm run sync:engine');}
 else fs.writeFileSync(file,expected);
}
if(require.main===module)sync({check:process.argv.includes('--check')});
module.exports={renderBrowserBundle,sync};
